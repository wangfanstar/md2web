const {chromium}=require('playwright');
const {spawn}=require('node:child_process');
const readline=require('node:readline');
const assert=require('node:assert/strict');
(async()=>{
 const server=spawn(process.env.MD2WEB_PYTHON||(process.platform==='win32'?'python':'python3'),['tests/browser/site-math-server.py'],{env:{...process.env,MD2WEB_MATH_SOURCE:'# AI'},stdio:['pipe','pipe','pipe']});
 let browser,stderr='';server.stderr.on('data',d=>stderr+=d);
 try{
  const base=await new Promise((resolve,reject)=>{readline.createInterface({input:server.stdout}).on('line',line=>{try{const d=JSON.parse(line);if(d.url)resolve(d.url);}catch{}});server.on('exit',()=>reject(new Error(stderr)));});
  browser=await chromium.launch({headless:true,executablePath:process.env.MD2WEB_BROWSER});
  const page=await browser.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
  console.log('fixture ready',base);
  await page.request.post(base+'/__auth/login',{data:{username:'alice',password:'good'}});
  await page.goto(base+'/html/index_server_only.html#/md/old/math');
  console.log('page loaded',await page.title());
  await page.waitForFunction(()=>window.SiteAuth?.isAuthenticated()&&window.AIAssistant,{},{timeout:10000});
  console.log('authenticated');
  await page.evaluate(()=>{localStorage.setItem('md2web:ai-config','secret');return AIAssistant.ready();});
  assert.equal(await page.evaluate(()=>localStorage.getItem('md2web:ai-config')),null);
  await page.route('**/__ai/public',route=>route.fulfill({json:{enabled:true,defaultRepository:'repo',repositories:[{id:'repo',name:'Test Repo',revision:'12',ready:true}],documentFolders:[{path:'md',available:true},{path:'manuals',available:true}]}}));
  const requests=[];
  await page.route('**/__ai/chat',route=>{const body=route.request().postDataJSON();requests.push(body);return route.fulfill({contentType:'text/event-stream',body:'event: start\ndata: {"jobId":"test"}\n\nevent: complete\ndata: '+JSON.stringify({answer:'result 42',repository:body.codeRepositoryId,revision:body.codeRepositoryId?'12':'',sources:body.codeRepositoryId?['main.py']:[],documentFolders:body.documentFolders,documentSources:body.documentFolders.map(p=>p+'/guide.md')})+'\n\n'});});
  await page.evaluate(()=>AIAssistant.open());
  await page.waitForFunction(()=>document.querySelector('[data-code-repository] option[value="repo"]'));
  assert.equal(await page.locator('[data-code-repository]').inputValue(),'');
  assert.equal(await page.locator('[data-document-folder][value="md"]').isChecked(),true);
  assert.equal(await page.locator('[data-document-folder][value="manuals"]').isChecked(),false);
  assert.equal(await page.locator('[data-ai-action="config"]').isVisible(),false);
  assert.equal(await page.locator('[data-ai-file]').count(),0);
  await page.evaluate(()=>AIAssistant.ask('frobnicate default'));
  assert.equal(requests[0].codeRepositoryId,'');assert.deepEqual(requests[0].documentFolders,['md']);
  assert.ok((await page.locator('[data-ai-messages]').innerText()).includes('未使用代码库'));
  await page.locator('[data-code-repository]').selectOption('repo');
  await page.locator('[data-document-folder][value="manuals"]').check();
  await page.evaluate(()=>AIAssistant.ask('frobnicate with code'));
  assert.equal(requests[1].codeRepositoryId,'repo');assert.deepEqual(requests[1].documentFolders,['md','manuals']);
  assert.equal(requests[1].messages.length,1,'scope changes discard old conversation context');
  assert.ok((await page.locator('[data-ai-messages]').innerText()).includes('r12'));
  await page.reload();await page.waitForFunction(()=>window.SiteAuth?.isAuthenticated()&&window.AIAssistant);
  await page.evaluate(()=>AIAssistant.open());await page.waitForFunction(()=>document.querySelector('[data-code-repository] option[value="repo"]'));
  await page.evaluate(()=>AIAssistant.ask('docs after reload'));
  assert.equal(requests[2].codeRepositoryId,'');assert.equal(requests[2].messages.length,1,'reloaded default scope excludes previous code answers');
  await page.evaluate(()=>AIAssistant.openConfig());assert.equal(await page.locator('[data-json]').count(),0);
  await page.request.post(base+'/__auth/login',{data:{username:'admin',password:'admin',mode:'admin'}});
  await page.evaluate(()=>SiteAuth.refresh());
  await page.evaluate(()=>AIAssistant.openConfig());
  await page.waitForFunction(()=>document.querySelector('[data-json]')?.value.includes('claude'));
  const config=JSON.parse(await page.locator('[data-json]').inputValue());
  assert.equal(config.claude.enabled,false);
  await page.locator('[data-document-folders]').fill('md\nmanuals');
  await page.locator('[data-code-folder]').fill('code/versions');
  await page.locator('[data-daily-time]').fill('04:30');
  await page.locator('[data-add-repo]').click();
  await page.locator('[data-code-repo-field="folder"]').fill('项目/v1');
  await page.locator('[data-code-repo-field="url"]').fill('https://svn.example.com/project');
  await page.locator('[data-code-repo-field="username"]').fill('sync-user');
  await page.locator('[data-code-repo-field="password"]').fill('private-password');
  await page.locator('[data-save]').click();
  await page.waitForFunction(()=>document.querySelector('[data-status]').textContent.includes('已保存'));
  const saved=(await (await page.request.get(base+'/__config')).json()).config.ai.claude;
  assert.equal(saved.codeFolder,'code/versions');assert.equal(saved.dailySyncTime,'04:30');assert.deepEqual(saved.documentFolders,['md','manuals']);assert.equal(saved.repositories[0].password,'private-password');
  await page.locator('[data-purge]').click();
  await page.waitForFunction(()=>document.querySelector('[data-status]').textContent.includes('已清理'));
  await page.evaluate(()=>SiteAuth.logout());
  assert.equal(await page.locator('[data-json]').count(),0,'logout clears administrator secrets');
  assert.deepEqual(errors,[]);
  console.log('Public AI browser checks passed');
 }finally{if(browser)await browser.close();server.stdin.end('\n');}
})().catch(e=>{console.error(e);process.exitCode=1;});
